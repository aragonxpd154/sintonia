_RE_SEG = re.compile(r"^(\d+) Segment$")
_RE_PKT = re.compile(r"^(\d+) packets?$")
_RE_TI = re.compile(r"^(\d+) \(mode 1\); (\d+) \(mode 2\); (\d+) \(mode 3\)$")


def titulo(t):
    if t is None:
        return ""
    s = TITULOS.get(t)
    if s is not None:
        return s
    s = TITULOS.get(t.strip())
    if s is not None:
        return s
    return t.strip()


def item(t):
    s = ITENS.get(t)
    if s is not None:
        return s
    m = _RE_SEG.match(t)
    if m:
        n = int(m.group(1))
        return "%d segmento%s" % (n, "" if n == 1 else "s")
    m = _RE_PKT.match(t)
    if m:
        n = int(m.group(1))
        return "%d pacote%s" % (n, "" if n == 1 else "s")
    m = _RE_TI.match(t)
    if m:
        return "I=%s / %s / %s (modos 1/2/3)" % m.groups()
    if t.startswith("Mode ") and t[5:].isdigit():
        return "Modo " + t[5:]
    return t
